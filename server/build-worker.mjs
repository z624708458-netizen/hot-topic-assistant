// Build a standalone ES module for Cloudflare dashboard deployment. No dependencies.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
export function build(){
 const contract=readFileSync(new URL('assets/speech-contract.js',root),'utf8');
 const worker=readFileSync(new URL('server/worker.mjs',root),'utf8');
 const dependency="import '../assets/speech-contract.js';";
 if(worker.split(dependency).length!==2)throw new Error('Unexpected Worker dependency; review bundle builder');
 return '// Generated by node server/build-worker.mjs. No secrets. Model disabled by default.\n'+contract+'\n'+worker.replace(dependency,'');
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const target=new URL('server/worker.bundle.mjs',root),content=build();
 if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==content)throw new Error('Worker bundle is stale: run node server/build-worker.mjs');}
 else writeFileSync(target,content);
}
